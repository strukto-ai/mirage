// The lines that open every file curl -c writes (curl 8.14.1); readers look
// for the first.
export const JAR_HEADER =
  '# Netscape HTTP Cookie File\n' +
  '# https://curl.se/docs/http-cookies.html\n' +
  '# This file was generated by libcurl! Edit at your own risk.\n\n'

// What a cookie file puts before the domain of an HttpOnly cookie.
export const HTTP_ONLY_PREFIX = '#HttpOnly_'

// No cookie outlives 400 days from its arrival (RFC 6265bis); curl rounds
// the capped time up to a whole minute.
export const MAX_LIFETIME = 400 * 24 * 60 * 60

// The hosts that take and get a Secure cookie over plain http.
export const SECURE_HOSTS: ReadonlySet<string> = new Set(['localhost', '127.0.0.1', '::1'])

const MONTHS = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec']

// RFC 822's zones, hours east of UTC.
export const ZONES: Readonly<Record<string, number>> = {
  gmt: 0,
  ut: 0,
  utc: 0,
  z: 0,
  est: -5,
  edt: -4,
  cst: -6,
  cdt: -5,
  mst: -7,
  mdt: -6,
  pst: -8,
  pdt: -7,
}

const DATE_TOKEN = /[+-][0-9]{4}(?![0-9])|[0-9]{1,2}:[0-9]{1,2}(?::[0-9]{1,2})?|[A-Za-z]+|[0-9]+/g
const IPV4 = /^[0-9]{1,3}(?:\.[0-9]{1,3}){3}$/

export interface Cookie {
  name: string
  value: string
  // Without the leading dot a file writes for a domain cookie. Null for a
  // Set-Cookie line a file gave without a Domain: it goes to every host and
  // is never saved (curl 8.14.1).
  domain: string | null
  // Whether the cookie also goes to subdomains, which a Domain attribute
  // asks for.
  tailmatch: boolean
  // As the server or the file gave it. Null for a Set-Cookie line a file
  // gave without a Path: it covers every path, sorts after them all and is
  // saved as `/` (curl 8.14.1).
  path: string | null
  secure: boolean
  httpOnly: boolean
  // Seconds since the epoch; 0 for a session cookie.
  expires: number
  // Arrival order, which a replaced cookie keeps.
  created: number
}

export function epochNow(): number {
  return Math.floor(Date.now() / 1000)
}

// Space and tab off both ends, the blanks RFC 6265 strips.
// A control byte, which no cookie name or value may hold (curl 8.14.1).
function hasControl(text: string): boolean {
  for (let i = 0; i < text.length; i += 1) {
    const code = text.charCodeAt(i)
    if (code < 0x20 || code === 0x7f) return true
  }
  return false
}

function trimWs(text: string): string {
  let start = 0
  let end = text.length
  while (start < end && (text[start] === ' ' || text[start] === '\t')) start += 1
  while (end > start && (text[end - 1] === ' ' || text[end - 1] === '\t')) end -= 1
  return text.slice(start, end)
}

/**
 * The seconds since the epoch an Expires attribute names, null when it does
 * not parse.
 *
 * The forms curl reads: a day of the month, a month name and a year in any
 * order, a time (midnight without one), and a zone, RFC 822's names or a
 * `+hhmm` offset (UTC without one). A two-digit year above 70 is in the
 * 1900s, the rest in the 2000s, and a date before 1970 does not parse
 * (curl 8.14.1). Zone names past RFC 822's are a deliberate gap: curl knows
 * more of them.
 */
export function parseDate(text: string): number | null {
  let day: number | null = null
  let month: number | null = null
  let year: number | null = null
  let time: [number, number, number] | null = null
  let offset = 0
  for (const [token] of text.matchAll(DATE_TOKEN)) {
    if (token.startsWith('+') || token.startsWith('-')) {
      const hhmm = Number(token.slice(1))
      const sign = token.startsWith('-') ? -1 : 1
      offset = sign * (Math.floor(hhmm / 100) * 3600 + (hhmm % 100) * 60)
    } else if (token.includes(':')) {
      if (time !== null) continue
      const [h = 0, m = 0, s = 0] = token.split(':').map(Number)
      if (h > 23 || m > 59 || s > 59) return null
      time = [h, m, s]
    } else if (/^[A-Za-z]/.test(token)) {
      const lower = token.toLowerCase()
      const named = MONTHS.indexOf(lower.slice(0, 3))
      if (named >= 0 && month === null && lower.length >= 3) month = named
      else if (lower in ZONES) offset = (ZONES[lower] ?? 0) * 3600
    } else if (token.length === 4) {
      year ??= Number(token)
    } else if (token.length <= 2) {
      const n = Number(token)
      if (day === null) day = n
      else year ??= n <= 70 ? 2000 + n : 1900 + n
    } else {
      return null
    }
  }
  if (day === null || month === null || year === null || day < 1 || day > 31) return null
  if (year < 1970) return null
  const [h, m, s] = time ?? [0, 0, 0]
  const epoch = Date.UTC(year, month, day, h, m, s) / 1000 - offset
  return epoch < 0 ? null : epoch
}

/** The request a URL makes, as cookie matching sees it. */
function target(url: string): { host: string; path: string; secure: boolean } | null {
  let parsed: URL
  try {
    parsed = new URL(url)
  } catch {
    return null
  }
  const host = parsed.hostname.replace(/^\[|\]$/g, '').toLowerCase()
  return {
    host,
    path: parsed.pathname === '' ? '/' : parsed.pathname,
    secure: parsed.protocol === 'https:' || SECURE_HOSTS.has(host),
  }
}

function isIp(host: string): boolean {
  return IPV4.test(host) || host.includes(':')
}

/**
 * The path a cookie set without one takes: the request's up to and including
 * its last slash. curl keeps that slash, which RFC 6265 drops, and the
 * matching below ignores it.
 */
export function defaultPath(path: string): string {
  const cut = path.lastIndexOf('/')
  return cut <= 0 ? '/' : path.slice(0, cut + 1)
}

// The path a cookie matches with: one that does not start with a slash
// covers everything, and a trailing slash is dropped (curl 8.14.1).
function pathKey(cookiePath: string | null): string {
  if (cookiePath?.startsWith('/') !== true) return '/'
  return cookiePath.length > 1 && cookiePath.endsWith('/') ? cookiePath.slice(0, -1) : cookiePath
}

/**
 * Whether a cookie's path covers a request's: RFC 6265's rule, the same path
 * or one below it, over the path the cookie matches with.
 */
export function pathMatches(cookiePath: string | null, path: string): boolean {
  const own = pathKey(cookiePath)
  if (path === own) return true
  return path.startsWith(own) && (own.endsWith('/') || path[own.length] === '/')
}

function domainMatches(cookie: Cookie, host: string): boolean {
  if (cookie.domain === null) return true
  const domain = cookie.domain.toLowerCase()
  return host === domain || (cookie.tailmatch && host.endsWith(`.${domain}`))
}

function sameCookie(a: Cookie, b: Cookie): boolean {
  return (
    a.name === b.name &&
    (a.domain ?? '').toLowerCase() === (b.domain ?? '').toLowerCase() &&
    pathKey(a.path) === pathKey(b.path)
  )
}

/**
 * The Cookie value a request carries: the jar's part, then the typed one.
 * A deliberate divergence: curl sends the two as separate Cookie lines, and
 * one line joined with `; ` reads the same to a server (node joins them so).
 */
export function cookieValue(part: string | null, typed: string | null): string | null {
  const pieces = [part, typed].filter((piece): piece is string => piece !== null && piece !== '')
  return pieces.length === 0 ? null : pieces.join('; ')
}

/**
 * curl's cookie engine for one invocation: what -b loads, what each response
 * sets, what each request sends, and the file -c writes.
 *
 * Matching follows curl 8.14.1 where it parts from RFC 6265: a Secure cookie
 * also rides plain http to localhost, 127.0.0.1 and ::1, and a request sends
 * longer paths first, then longer names, then newer cookies. One deliberate
 * gap: curl refuses a Domain that is a public suffix (co.uk) through the
 * public suffix list, whose license mirage cannot ship, so only a suffix of
 * one label (com) is refused here. A host-only cookie's domain is the host
 * lowercase, as the URL parser hands it over, where curl keeps it as typed.
 */
export class CookieJar {
  // Oldest first.
  readonly cookies: Cookie[] = []
  // The jar's part of each request's Cookie header, in the order sent;
  // curl -v shows it per hop.
  readonly sent: (string | null)[] = []
  private arrivals = 0

  constructor(
    // Whether the jar keeps what responses set: on once the line names a
    // cookie file or -c, off for literal -b data alone (curl 8.14.1).
    readonly engine: boolean,
    // The literal -b data, sent to every host after the jar's cookies.
    readonly literal: string | null = null,
    readonly now: () => number = epochNow,
  ) {}

  private keep(cookie: Cookie, expired: boolean): void {
    const index = this.cookies.findIndex((other) => sameCookie(other, cookie))
    if (expired) {
      if (index >= 0) this.cookies.splice(index, 1)
      return
    }
    if (index >= 0) {
      const prior = this.cookies[index]
      this.cookies[index] = { ...cookie, created: prior?.created ?? cookie.created }
      return
    }
    this.arrivals += 1
    this.cookies.push({ ...cookie, created: this.arrivals })
  }

  /**
   * Add one Set-Cookie value. `url` is the request it answered, null for a
   * line a file gave, which no host, path or scheme constrains.
   */
  private add(header: string, url: string | null): void {
    const request = url === null ? null : target(url)
    if (url !== null && request === null) return
    const [pair = '', ...attributes] = header.split(';')
    const eq = pair.indexOf('=')
    if (eq < 0) return
    const name = trimWs(pair.slice(0, eq))
    const value = trimWs(pair.slice(eq + 1))
    if (hasControl(name) || hasControl(value)) return
    let expiresAt: number | null = null
    let maxAge: number | null = null
    let domainAttr: string | null = null
    let pathAttr: string | null = null
    let secure = false
    let httpOnly = false
    for (const attribute of attributes) {
      const sep = attribute.indexOf('=')
      const key = trimWs(sep < 0 ? attribute : attribute.slice(0, sep)).toLowerCase()
      const raw = sep < 0 ? '' : trimWs(attribute.slice(sep + 1))
      if (key === 'expires') {
        expiresAt = parseDate(raw) ?? expiresAt
      } else if (key === 'max-age') {
        // curl drops a cookie whose Max-Age does not start with a digit or a
        // minus, and reads the digits that lead one that does.
        const digits = /^-?[0-9]+/.exec(raw)
        if (digits === null) return
        maxAge = Number(digits[0])
      } else if (key === 'domain') {
        if (raw !== '') domainAttr = raw.replace(/^\./, '')
      } else if (key === 'path') {
        pathAttr = raw
      } else if (key === 'secure') {
        secure = true
      } else if (key === 'httponly') {
        httpOnly = true
      }
    }
    const now = this.now()
    let expires = 0
    let expired = false
    if (maxAge !== null) {
      expired = maxAge <= 0
      expires = expired ? 0 : now + Math.min(maxAge, MAX_LIFETIME + 1)
    } else if (expiresAt !== null) {
      expired = expiresAt <= now
      expires = expiresAt
    }
    if (expires > now + MAX_LIFETIME) expires = Math.ceil((now + MAX_LIFETIME) / 60) * 60
    let domain: string | null = domainAttr
    let tailmatch = domainAttr !== null
    let path = pathAttr
    if (request !== null) {
      path = pathAttr ?? defaultPath(request.path)
      if (domainAttr === null) {
        domain = request.host
      } else {
        const wanted = domainAttr.toLowerCase()
        if (isIp(request.host)) {
          if (wanted !== request.host) return
          domain = request.host
          tailmatch = false
        } else if (wanted === request.host || request.host.endsWith(`.${wanted}`)) {
          if (!wanted.includes('.') && wanted !== request.host) return
        } else {
          return
        }
      }
      if (secure && !request.secure) return
      if (name.startsWith('__Secure-') && !secure) return
      if (name.startsWith('__Host-') && (!secure || tailmatch || path !== '/')) return
    }
    this.keep(
      { name, value, domain, tailmatch, path, secure, httpOnly, expires, created: 0 },
      expired,
    )
  }

  /** Keep what one response to `url` set. */
  store(url: string, headers: readonly string[]): void {
    if (!this.engine) return
    for (const header of headers) this.add(header, url)
  }

  /**
   * Load a cookie file: curl's tab-separated lines, `#HttpOnly_` marking a
   * domain, or `Set-Cookie:` header lines. A line that does not parse, and a
   * cookie already expired, are skipped (curl 8.14.1).
   */
  load(text: string): void {
    for (const raw of text.split('\n')) {
      let line = raw.endsWith('\r') ? raw.slice(0, -1) : raw
      if (/^set-cookie:/i.test(line)) {
        this.add(line.slice('set-cookie:'.length).trimStart(), null)
        continue
      }
      let httpOnly = false
      if (line.startsWith(HTTP_ONLY_PREFIX)) {
        httpOnly = true
        line = line.slice(HTTP_ONLY_PREFIX.length)
      } else if (line === '' || line.startsWith('#')) {
        continue
      }
      const fields = line.split('\t')
      if (fields.length === 6) fields.push('')
      if (fields.length !== 7) continue
      const [domain = '', tail = '', path = '', secure = '', expiry = '', name = '', value = ''] =
        fields
      const digits = /^[0-9]+/.exec(expiry)
      if (digits === null) continue
      const expires = Number(digits[0])
      if (expires !== 0 && expires <= this.now()) continue
      this.keep(
        {
          name,
          value,
          domain: domain.replace(/^\./, ''),
          tailmatch: tail.toUpperCase() === 'TRUE',
          path,
          secure: secure.toUpperCase() === 'TRUE',
          httpOnly,
          expires,
          created: 0,
        },
        false,
      )
    }
  }

  /** The jar's part of the Cookie header a request to `url` sends. */
  header(url: string): string | null {
    const request = target(url)
    const now = this.now()
    const pairs =
      !this.engine || request === null
        ? []
        : this.cookies
            .filter(
              (c) =>
                (c.expires === 0 || c.expires > now) &&
                domainMatches(c, request.host) &&
                pathMatches(c.path, request.path) &&
                (!c.secure || request.secure),
            )
            .sort(
              (a, b) =>
                (b.path?.length ?? 0) - (a.path?.length ?? 0) ||
                b.name.length - a.name.length ||
                b.created - a.created,
            )
            .map((c) => `${c.name}=${c.value}`)
    if (this.literal !== null) pairs.push(this.literal)
    const value = pairs.length === 0 ? null : pairs.join('; ')
    this.sent.push(value)
    return value
  }

  /** The file -c writes: every live cookie with a domain, newest first. */
  render(): string {
    const now = this.now()
    const lines = this.cookies
      .filter((c) => c.domain !== null && (c.expires === 0 || c.expires > now))
      .sort((a, b) => b.created - a.created)
      .map((c) =>
        [
          `${c.httpOnly ? HTTP_ONLY_PREFIX : ''}${c.tailmatch ? '.' : ''}${c.domain ?? ''}`,
          c.tailmatch ? 'TRUE' : 'FALSE',
          c.path ?? '/',
          c.secure ? 'TRUE' : 'FALSE',
          String(c.expires),
          c.name,
          c.value,
        ].join('\t'),
      )
    return JAR_HEADER + lines.map((line) => `${line}\n`).join('')
  }
}
