import { S_IFDIR, S_IFREG } from '../../utils/stat_view.ts'
import { SqlDialect } from '../../vfs/sql/types.ts'

/** The inode every path resolves from. */
export const ROOT_INO = 1

/**
 * The bytes one `fs_data` row holds in a database the mount makes: AgentFS's
 * default. A database made with another size keeps it (`fs_config`), and the
 * ops read and write rows of that size.
 */
export const DEFAULT_CHUNK_SIZE = 4096

/** What `fs_inode.mode` holds: the type bits alone. */
export const DIR = S_IFDIR
export const FILE = S_IFREG

/** The most parameters one statement binds: D1 and Durable Objects stop at 100. */
export const MAX_PARAMS = 100

/** The most columns one query answers: D1 and Durable Objects stop at 100. */
export const MAX_COLUMNS = 100

/** The bytes a streamed write gathers before it lands them. */
export const FLUSH_BYTES = 1024 * 1024

/** The columns of `fs_inode` the ops read. */
export const INODE_COLUMNS = ['ino', 'mode', 'size', 'mtime', 'mtime_nsec'] as const

/** `INODE_COLUMNS` read off the table aliased `alias`. */
export function columns(alias: string): string {
  return INODE_COLUMNS.map((c) => `${alias}.${c}`).join(', ')
}

// The chunk size a fresh database starts with; a no-op on one that has it, so
// opening one another runtime made keeps what it holds.
const SEED = `INSERT INTO fs_config (key, value) SELECT 'chunk_size', '${String(DEFAULT_CHUNK_SIZE)}'
    WHERE NOT EXISTS (SELECT 1 FROM fs_config WHERE key = 'chunk_size')`

/**
 * The tables a database holds a filesystem in, by dialect, laid out as
 * AgentFS's: an inode is one file or directory, with its size and mtime; a
 * dentry names it under its parent; a file's bytes are its `fs_data` rows,
 * `chunk_size` bytes each. The index on `fs_dentry(ino)` lets a removal ask
 * whether any entry still names an inode without reading others.
 */
export const SCHEMA: Readonly<Record<SqlDialect, readonly string[]>> = {
  [SqlDialect.SQLITE]: [
    'CREATE TABLE IF NOT EXISTS fs_config (key TEXT PRIMARY KEY, value TEXT NOT NULL)',
    `CREATE TABLE IF NOT EXISTS fs_inode (
      ino INTEGER PRIMARY KEY AUTOINCREMENT, mode INTEGER NOT NULL,
      size INTEGER NOT NULL DEFAULT 0, mtime INTEGER NOT NULL,
      mtime_nsec INTEGER NOT NULL DEFAULT 0)`,
    `CREATE TABLE IF NOT EXISTS fs_dentry (
      id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL,
      parent_ino INTEGER NOT NULL, ino INTEGER NOT NULL, UNIQUE(parent_ino, name))`,
    'CREATE INDEX IF NOT EXISTS idx_fs_dentry_ino ON fs_dentry(ino)',
    `CREATE TABLE IF NOT EXISTS fs_data (
      ino INTEGER NOT NULL, chunk_index INTEGER NOT NULL, data BLOB NOT NULL,
      PRIMARY KEY (ino, chunk_index))`,
    SEED,
  ],
  // The root is inode 1, so the generated numbers start past it.
  [SqlDialect.POSTGRES]: [
    'CREATE TABLE IF NOT EXISTS fs_config (key TEXT PRIMARY KEY, value TEXT NOT NULL)',
    `CREATE TABLE IF NOT EXISTS fs_inode (
      ino BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
      mode BIGINT NOT NULL, size BIGINT NOT NULL DEFAULT 0, mtime BIGINT NOT NULL,
      mtime_nsec BIGINT NOT NULL DEFAULT 0)`,
    `CREATE TABLE IF NOT EXISTS fs_dentry (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,
      parent_ino BIGINT NOT NULL, ino BIGINT NOT NULL, UNIQUE(parent_ino, name))`,
    'CREATE INDEX IF NOT EXISTS idx_fs_dentry_ino ON fs_dentry(ino)',
    `CREATE TABLE IF NOT EXISTS fs_data (
      ino BIGINT NOT NULL, chunk_index BIGINT NOT NULL, data BYTEA NOT NULL,
      PRIMARY KEY (ino, chunk_index))`,
    SEED,
  ],
}

/** How a statement names the inode the statement before it inserted, by dialect. */
export const LAST_INO: Readonly<Record<SqlDialect, string>> = {
  [SqlDialect.SQLITE]: 'last_insert_rowid()',
  [SqlDialect.POSTGRES]: "currval(pg_get_serial_sequence('fs_inode', 'ino'))",
}

// The number a restore's inodes count from, which it keeps in `fs_config`
// while it runs: the one the database gives an inode made just before, past
// every number it gave out, so no op that read an inode before the restore
// reaches one it made.
const RESTORE_BASE = "(SELECT CAST(value AS BIGINT) FROM fs_config WHERE key = 'restore_base')"

/** How a restore names its `k`th inode: past the base, so the walk needs no lookup. */
export const RESTORED_INO = `(${RESTORE_BASE} + CAST(? AS BIGINT))`

/**
 * What runs after a restore numbered its inodes, by dialect: Postgres's
 * sequence moves past them; SQLite's follows its rows.
 */
export const RENUMBERED: Readonly<Record<SqlDialect, string | null>> = {
  [SqlDialect.SQLITE]: null,
  [SqlDialect.POSTGRES]: `SELECT setval(pg_get_serial_sequence('fs_inode', 'ino'),
    GREATEST((SELECT MAX(ino) FROM fs_inode), ${RESTORE_BASE}))`,
}

/**
 * Every fixed statement the sql ops run, by name. Python's `SQL` holds the
 * same text, so the two runtimes read and write one database alike.
 */
export const SQL = {
  chunkSize: "SELECT value FROM fs_config WHERE key = 'chunk_size'",
  inode: `SELECT ${columns('i')} FROM fs_inode i WHERE i.ino = ?`,
  // The root, made at the time `?` gives unless the database has one. The
  // cast types the parameter, which a SELECT list leaves untyped in Postgres.
  seedRoot: `INSERT INTO fs_inode (ino, mode, size, mtime)
    SELECT ${String(ROOT_INO)}, ${String(DIR)}, 0, CAST(? AS BIGINT)
    WHERE NOT EXISTS (SELECT 1 FROM fs_inode WHERE ino = ${String(ROOT_INO)})`,
  children: `SELECT d.name, ${columns('i')}
    FROM fs_dentry d JOIN fs_inode i ON i.ino = d.ino
    WHERE d.parent_ino = ?`,
  entry: `SELECT ${columns('i')}
    FROM fs_dentry d JOIN fs_inode i ON i.ino = d.ino
    WHERE d.parent_ino = ? AND d.name = ?`,
  hasChild: 'SELECT 1 AS hit FROM fs_dentry WHERE parent_ino = ? LIMIT 1',
  hasEntry: 'SELECT 1 AS hit FROM fs_dentry WHERE parent_ino = ? AND name = ?',
  // Every entry under one directory, each with its depth below it and its
  // path from it.
  subtree: `WITH RECURSIVE tree (id, ino, depth, rel) AS (
      SELECT id, ino, 1, name FROM fs_dentry WHERE parent_ino = ?
      UNION ALL
      SELECT d.id, d.ino, t.depth + 1, t.rel || '/' || d.name
      FROM fs_dentry d JOIN tree t ON d.parent_ino = t.ino)
    SELECT t.id, t.depth, t.rel, ${columns('i')}
    FROM tree t JOIN fs_inode i ON i.ino = t.ino`,
  chunks: `SELECT chunk_index, data FROM fs_data
    WHERE ino = ? AND chunk_index >= ? AND chunk_index <= ? ORDER BY chunk_index`,
  usedBytes: `SELECT COALESCE(SUM(size), 0) AS n FROM fs_inode WHERE mode = ${String(FILE)}`,
  newInode: 'INSERT INTO fs_inode (mode, size, mtime, mtime_nsec) VALUES (?, ?, ?, ?)',
  setBase: `INSERT INTO fs_config (key, value)
    SELECT 'restore_base', CAST(MAX(ino) AS TEXT) FROM fs_inode`,
  dropBase: "DELETE FROM fs_config WHERE key = 'restore_base'",
  removeEntry: 'DELETE FROM fs_dentry WHERE parent_ino = ? AND name = ?',
  // The new parent through its inode, so one removed since the lookup
  // fails the move rather than strand the entry.
  moveEntry: `UPDATE fs_dentry SET parent_ino = (SELECT ino FROM fs_inode WHERE ino = ?), name = ?
    WHERE parent_ino = ? AND name = ?`,
} as const

/** What `restore` empties before it writes a snapshot back. */
export const CLEAR: readonly string[] = [
  'DELETE FROM fs_data',
  'DELETE FROM fs_dentry',
  `DELETE FROM fs_inode WHERE ino <> ${String(ROOT_INO)}`,
]

/**
 * What `restore` empties of a mount on a folder of its database: the
 * folder's files, entries and inodes, and the inode the restore counts
 * from, which the folder does not hold. Each statement walks the folder's
 * entries again, so the entries go last.
 */
export function clearUnder(ino: number): string[] {
  const tree = `WITH RECURSIVE tree (id, ino) AS (
      SELECT id, ino FROM fs_dentry WHERE parent_ino = ${String(Math.trunc(ino))}
      UNION ALL
      SELECT d.id, d.ino FROM fs_dentry d JOIN tree t ON d.parent_ino = t.ino)`
  return [
    `DELETE FROM fs_data WHERE ino IN (${tree} SELECT ino FROM tree)`,
    `DELETE FROM fs_inode WHERE ino IN (${tree} SELECT ino FROM tree) OR ino = ${RESTORE_BASE}`,
    `DELETE FROM fs_dentry WHERE id IN (${tree} SELECT id FROM tree)`,
  ]
}
