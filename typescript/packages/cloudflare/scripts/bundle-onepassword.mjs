import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname } from 'node:path'

// 1Password's SDK core as a Worker can load it. The published core is
// wasm-bindgen's node build: its glue reads core_bg.wasm off disk and
// compiles it, and a Worker can do neither. The glue is kept as it is;
// only that last step is replaced, by importing the WebAssembly as a
// module, which wrangler compiles at upload. Generated from the
// installed core, so the glue and the WebAssembly always match.

// The core is the SDK's own dependency, so it resolves from the SDK.
const sdk = createRequire(import.meta.url).resolve('@1password/sdk')
const core = dirname(createRequire(sdk).resolve('@1password/sdk-core'))
const output = new URL('../src/generated/', import.meta.url)
mkdirSync(output, { recursive: true })

const code = readFileSync(`${core}/core.js`, 'utf8')
const load = "const path = require('path').join(__dirname, 'core_bg.wasm');"
const at = code.indexOf(load)
if (at < 0) throw new Error(`@1password/sdk-core's loader changed: ${load} is gone`)

writeFileSync(
  new URL('onepassword_core.js', output),
  `// Generated by scripts/bundle-onepassword.mjs from @1password/sdk-core
// (MIT, Copyright 1Password); only its WebAssembly load is changed.
import wasmModule from './onepassword_core.wasm'
import * as crypto from 'node:crypto'
// The glue's own requires: util for its text codecs, and crypto, which
// wasm-bindgen's getrandom reaches through module.require under node.
const require = (name) => {
  if (name === 'util') {
    return { TextDecoder: globalThis.TextDecoder, TextEncoder: globalThis.TextEncoder }
  }
  if (name === 'crypto') return crypto
  throw new Error(\`\${name} is not available in a Worker\`)
}
const module = { exports: {}, require }
${code.slice(0, at)}
wasm = new WebAssembly.Instance(wasmModule, imports).exports
module.exports.__wasm = wasm
wasm.__wbindgen_start()
export const { init_client, init_client_oidc, invoke, invoke_sync, release_client } = module.exports
`,
)
copyFileSync(`${core}/core_bg.wasm`, new URL('onepassword_core.wasm', output))
