import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent

SOURCE = ROOT / "scripts/rg_types.toml"
PY_OUT = ROOT / "python/mirage/utils/generated/rg_types.py"
TS_OUT = ROOT / "typescript/packages/core/src/utils/generated/rg_types.ts"

LICENSE_PY = (ROOT / "scripts/gen_specs.py").read_text().split("\n")[:13]

NOTE = (
    "GENERATED by scripts/gen_rg_types.py from scripts/rg_types.toml:\n"
    "ripgrep 14.1.1's built-in file types, each name and the globs a file's\n"
    "name is matched against (MIT; see licenses/third_party/ripgrep.txt).\n"
    "Do not edit by hand; edit the TOML, run the script and commit both\n"
    "trees' output together."
)

# Each tree's formatter width: a type whose globs fit stays on one line,
# a longer one takes a line per glob, as ruff and oxfmt lay them out.
PY_WIDTH = 79
TS_WIDTH = 100


# Written between quotes as they are, so each host reads the same glob.
UNQUOTABLE = frozenset("\\\"'")


def load() -> dict[str, list[str]]:
    table = tomllib.loads(SOURCE.read_text())
    for name, globs in table.items():
        if not name.isalnum() or name == "all":
            raise SystemExit(
                f"{SOURCE.name}: {name}: not a type name rg takes"
            )
        if not (
            isinstance(globs, list)
            and globs
            and all(
                isinstance(glob, str) and glob and not UNQUOTABLE & set(glob)
                for glob in globs
            )
            and len(set(globs)) == len(globs)
        ):
            raise SystemExit(f"{SOURCE.name}: {name}: want distinct globs")
    return {name: sorted(table[name]) for name in sorted(table)}


def py_entry(name: str, globs: list[str]) -> str:
    items = [f'"{glob}"' for glob in globs]
    inline = f"({items[0]},)" if len(items) == 1 else f"({', '.join(items)})"
    line = f'    "{name}": {inline},'
    if len(line) <= PY_WIDTH:
        return line
    rows = "".join(f"        {item},\n" for item in items)
    return f'    "{name}": (\n{rows}    ),'


def ts_entry(name: str, globs: list[str]) -> str:
    items = [f"'{glob}'" for glob in globs]
    key = name if name.isidentifier() else f"'{name}'"
    line = f"  {key}: [{', '.join(items)}],"
    if len(line) <= TS_WIDTH:
        return line
    rows = "".join(f"    {item},\n" for item in items)
    return f"  {key}: [\n{rows}  ],"


def main() -> None:
    table = load()
    py_head = "\n".join(LICENSE_PY)
    py_note = "\n".join(f"# {line}" for line in NOTE.split("\n"))
    py_rows = "\n".join(py_entry(name, globs) for name, globs in table.items())
    PY_OUT.write_text(
        f"{py_head}\n\n{py_note}\n\n"
        f"DEFAULT_TYPES: dict[str, tuple[str, ...]] = {{\n{py_rows}\n}}\n"
    )
    ts_head = "\n".join(line.replace("#", "//", 1) for line in LICENSE_PY)
    ts_note = "\n".join(f"// {line}" for line in NOTE.split("\n"))
    ts_rows = "\n".join(ts_entry(name, globs) for name, globs in table.items())
    TS_OUT.write_text(
        f"{ts_head}\n\n{ts_note}\n\n"
        "export const DEFAULT_TYPES: Readonly<Record<string, readonly "
        f"string[]>> = {{\n{ts_rows}\n}}\n"
    )
    print(f"{len(table)} types: wrote {PY_OUT.relative_to(ROOT)}")
    print(f"{len(table)} types: wrote {TS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
