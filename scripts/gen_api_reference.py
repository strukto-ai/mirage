import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "docs" / "openapi.yaml"
PAGE = ROOT / "docs" / "api" / "reference.mdx"
TAG_ORDER = (
    "Workspaces",
    "Sessions",
    "Shell",
    "VFS",
    "Tools",
    "Documents",
    "Snapshots",
    "Templates",
    "Saved VFS",
    "Saved CLIs",
    "Saved runtimes",
    "Policies",
    "Asks",
    "Server",
    "Auth",
)
METHOD_ORDER = ("get", "post", "put", "patch", "delete")
HEADER = """---
title: API reference
description: "Every route of the Mirage HTTP API, generated from openapi.yaml."
icon: list
---

import { ApiExplorer, Operation } from "/snippets/api-explorer.jsx"

{/* Generated by scripts/gen_api_reference.py from docs/openapi.yaml. Do not edit. */}

Routes are under `/v1` and take and return JSON. Send
`Authorization: Bearer <token>` when the server has a token set; see the
[overview](/api/overview) for launching a server, auth and errors. The
[OpenAPI document](https://github.com/strukto-ai/mirage/blob/main/docs/openapi.yaml)
is the contract both servers are checked against.

Rows marked **daemon and hosted** are also served by the hosted API.
An error answers `{detail, errno?, refusal?}`; `429` adds `Retry-After`.
"""


def escape(text: str) -> str:
    """Escape MDX's ``{``, ``}`` and ``<`` outside code.

    Args:
        text (str): Markdown prose.
    """
    out: list[str] = []
    fence = False
    for line in text.split("\n"):
        if line.lstrip().startswith("```"):
            fence = not fence
            out.append(line)
            continue
        if fence:
            out.append(line)
            continue
        parts = re.split(r"(`[^`]*`)", line)
        out.append(
            "".join(
                part
                if part.startswith("`")
                else part.replace("{", "\\{")
                .replace("}", "\\}")
                .replace("<", "&lt;")
                for part in parts
            )
        )
    return "\n".join(out)


def attr(text: str) -> str:
    """Quote a value for a JSX string attribute.

    Args:
        text (str): the raw value.
    """
    return text.replace("\\", "\\\\").replace('"', "&quot;")


def resolve(doc: dict[str, Any], node: dict[str, Any]) -> dict[str, Any]:
    """Follow a ``$ref`` to its component: a schema, parameter or
    response.

    Args:
        doc (dict[str, Any]): the OpenAPI document.
        node (dict[str, Any]): an object that may be a reference.
    """
    ref = node.get("$ref")
    if ref:
        _, _, kind, name = ref.split("/")
        return dict(doc["components"][kind][name])
    return node


def type_of(schema: dict[str, Any]) -> str:
    """A short type name for a schema.

    Args:
        schema (dict[str, Any]): the schema.
    """
    if "$ref" in schema:
        return str(schema["$ref"].rsplit("/", 1)[-1])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(type_of(s) for s in schema[key])
    kind = schema.get("type")
    if kind == "array":
        return f"{type_of(schema.get('items', {}))}[]"
    if isinstance(kind, list):
        return " | ".join(kind)
    encoding = schema.get("contentEncoding")
    if encoding:
        return f"{kind} ({encoding})"
    return str(kind or "any")


def flatten(doc: dict[str, Any], schema: dict[str, Any]) -> dict[str, Any]:
    """An object schema with its ``allOf`` parts merged into one set of
    properties and required names.

    Args:
        doc (dict[str, Any]): the OpenAPI document.
        schema (dict[str, Any]): the schema, or a reference to it.
    """
    obj = resolve(doc, schema)
    if "allOf" not in obj:
        return obj
    props: dict[str, Any] = {}
    required: list[str] = []
    for part in obj["allOf"]:
        merged = flatten(doc, part)
        props.update(merged.get("properties", {}))
        required += merged.get("required", [])
    return {"properties": props, "required": required}


def shapes(
    doc: dict[str, Any], schema: dict[str, Any]
) -> list[tuple[str, dict[str, Any]]]:
    """Each object a response body can be, named: every ``anyOf`` or
    ``oneOf`` branch, an array's items, or the schema itself.

    Args:
        doc (dict[str, Any]): the OpenAPI document.
        schema (dict[str, Any]): the response body's schema.
    """
    obj = resolve(doc, schema)
    for key in ("anyOf", "oneOf"):
        if key in obj:
            return [s for branch in obj[key] for s in shapes(doc, branch)]
    if obj.get("type") == "array":
        return shapes(doc, obj.get("items", {}))
    flat = flatten(doc, schema)
    if flat.get("properties"):
        return [(type_of(schema), flat)]
    return []


def fields(
    doc: dict[str, Any], schema: dict[str, Any], tag: str, place: str
) -> list[str]:
    """One ``ParamField`` or ``ResponseField`` per property of an object
    schema.

    Args:
        doc (dict[str, Any]): the OpenAPI document.
        schema (dict[str, Any]): the object schema, or a reference to it.
        tag (str): ``ParamField`` or ``ResponseField``.
        place (str): ``body`` for a request, empty for a response.
    """
    obj = flatten(doc, schema)
    required = set(obj.get("required", []))
    lines: list[str] = []
    for name, prop in obj.get("properties", {}).items():
        key = f'{place}="{name}"' if place else f'name="{name}"'
        flag = " required" if name in required else ""
        text = escape(prop.get("description", "").strip())
        lines.append(f'<{tag} {key} type="{attr(type_of(prop))}"{flag}>')
        if text:
            lines.append(text)
        lines.append(f"</{tag}>")
    return lines


def slug(text: str) -> str:
    """The URL segment Mintlify derives from a title.

    Args:
        text (str): a tag or summary.
    """
    kept = re.sub(r"[^a-z0-9 _-]", "", text.lower())
    return re.sub(r"\s+", "-", kept.strip())


def operation(
    doc: dict[str, Any], path: str, method: str, op: dict[str, Any]
) -> list[str]:
    """The ``Operation`` block for one route.

    Args:
        doc (dict[str, Any]): the OpenAPI document.
        path (str): the route's path.
        method (str): its lower-case method.
        op (dict[str, Any]): the operation object.
    """
    hosts = " · ".join(op.get("x-hosts", ["daemon"]))
    lines = [
        f'<Operation resource="{attr(op["tags"][0])}" '
        f'method="{method.upper()}" path="{attr(path)}" '
        f'summary="{attr(op["summary"])}" hosts="{attr(hosts)}">',
        "",
    ]
    page = f"/api/operations/{slug(op['tags'][0])}/{slug(op['summary'])}"
    lines += [f"[Open page]({page})", ""]
    if op.get("description"):
        lines += [escape(op["description"].strip()), ""]
    params = [resolve(doc, p) for p in op.get("parameters", [])]
    for place, title in (
        ("path", "Path"),
        ("query", "Query"),
        ("header", "Header"),
    ):
        chosen = [p for p in params if p["in"] == place]
        if chosen:
            lines += [f"**{title}**", ""]
        for param in chosen:
            flag = " required" if param.get("required") else ""
            text = escape(param.get("description", "").strip())
            lines.append(
                f'<ParamField {place}="{param["name"]}" '
                f'type="{attr(type_of(param.get("schema", {})))}"{flag}>'
            )
            if text:
                lines.append(text)
            lines.append("</ParamField>")
        if chosen:
            lines.append("")
    body = op.get("requestBody", {}).get("content", {})
    for kind, media in body.items():
        lines += [f"**Body** `{kind}`", ""]
        lines += fields(doc, media.get("schema", {}), "ParamField", "body")
        lines.append("")
    lines += ["**Responses**", ""]
    for code, raw in op.get("responses", {}).items():
        response = resolve(doc, raw)
        text = escape(response.get("description", "").strip())
        lines += [f"`{code}` {text}", ""]
        if "$ref" in raw:
            continue
        for kind, media in response.get("content", {}).items():
            schema = media.get("schema", {})
            lines += [f"`{kind}` `{attr(type_of(schema))}`", ""]
            found = shapes(doc, schema)
            choice = any(k in resolve(doc, schema) for k in ("anyOf", "oneOf"))
            for name, shape in found:
                if choice or len(found) > 1:
                    lines += [f"*{name}*", ""]
                lines += fields(doc, shape, "ResponseField", "")
                lines.append("")
    lines += ["</Operation>", ""]
    return lines


def order(item: tuple[str, str, dict[str, Any]]) -> tuple[int, str, int]:
    """Where an operation sits on the page: by resource, then path, then
    method.

    Args:
        item (tuple[str, str, dict[str, Any]]): ``(path, method, op)``.
    """
    path, method, op = item
    tag = op["tags"][0]
    rank = TAG_ORDER.index(tag) if tag in TAG_ORDER else len(TAG_ORDER)
    return rank, path, METHOD_ORDER.index(method)


def render(doc: dict[str, Any]) -> str:
    """The whole reference page.

    Args:
        doc (dict[str, Any]): the OpenAPI document.
    """
    ops = [
        (path, method, op)
        for path, methods in doc["paths"].items()
        for method, op in methods.items()
        if method in METHOD_ORDER
    ]
    lines = [HEADER, "<ApiExplorer>", ""]
    for path, method, op in sorted(ops, key=order):
        lines += operation(doc, path, method, op)
    lines.append("</ApiExplorer>")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the committed page differs from the generated one",
    )
    args = parser.parse_args()
    page = render(yaml.safe_load(SPEC.read_text()))
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != page:
            print(
                f"{PAGE.relative_to(ROOT)} is stale; run "
                "python scripts/gen_api_reference.py"
            )
            return 1
        print(f"{PAGE.relative_to(ROOT)} is up to date")
        return 0
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(page)
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
