import hashlib
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
RS_OUT = ROOT / "rust/mirage-rs/src/generated/unicode_width.rs"

# The Unicode version GNU coreutils 9.7 on glibc 2.41 (the image the integ
# pins were taken against) measures text by. Only Unicode's own data files
# are read, under the Unicode License; the rules below come from UAX #11
# and the character properties, and integ's wc cases check them against
# GNU's output.
VERSION = "16.0.0"
FILES = {
    "UnicodeData.txt": (
        "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"
    ),
    "EastAsianWidth.txt": (
        "43adc76c0686a42cb370764eb8cfe2b2a45b10b855e5572a2db4a0eecce15d5b"
    ),
    "PropList.txt": (
        "53d614508e2a0b2305a8aa21cd60d993de9326cdf65993660dfcce4503548583"
    ),
}


def fetch(name: str) -> str:
    url = f"https://www.unicode.org/Public/{VERSION}/ucd/{name}"
    request = urllib.request.Request(url, headers={"User-Agent": "mirage"})
    with urllib.request.urlopen(request) as response:
        data: bytes = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != FILES[name]:
        raise SystemExit(f"{name}: sha256 {digest}, want {FILES[name]}")
    return data.decode("utf-8")


def entries(text: str) -> list[tuple[range, str]]:
    out = []
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        cps, value = (part.strip() for part in line.split(";")[:2])
        lo, _, hi = cps.partition("..")
        out.append((range(int(lo, 16), int(hi or lo, 16) + 1), value))
    return out


def categories(text: str) -> tuple[dict[int, str], set[int]]:
    category: dict[int, str] = {}
    nobreak: set[int] = set()
    first = 0
    for line in text.splitlines():
        fields = line.split(";")
        cp, name, gc = int(fields[0], 16), fields[1], fields[2]
        if fields[5].startswith("<noBreak>"):
            nobreak.add(cp)
        if name.endswith(", First>"):
            first = cp
        elif name.endswith(", Last>"):
            category.update(dict.fromkeys(range(first, cp + 1), gc))
        else:
            category[cp] = gc
    return category, nobreak


def width(cp: int, gc: str, east_asian: str, concatenation: set[int]) -> int:
    """Columns one code point takes, -1 for one that does not print."""
    # Controls, surrogates, unassigned code points and the line and
    # paragraph separators do not print.
    if gc in ("Cc", "Cs", "Cn", "Zl", "Zp"):
        return -1
    # The Hangul fillers are letters that show nothing.
    if cp in (0x3164, 0xFFA0):
        return 0
    # Circled numbers on black squares, East Asian ambiguous since
    # Unicode 9 and still wide on a terminal.
    if 0x3248 <= cp <= 0x324F:
        return 2
    # Format characters that draw: the interlinear annotation marks and
    # the Egyptian hieroglyph format controls.
    if 0xFFF9 <= cp <= 0xFFFB or 0x13430 <= cp <= 0x1343F:
        return 1
    # Combining and enclosing marks and format characters take no column,
    # except the soft hyphen and the prepended concatenation marks, which
    # print before the digits they span.
    if gc in ("Mn", "Me", "Cf") and cp != 0x00AD and cp not in concatenation:
        return 0
    # Hangul medial vowels and final consonants join the syllable before.
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF:
        return 0
    if east_asian in ("W", "F"):
        return 2
    return 1


def ranges(codes: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in codes:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def rows(spans: list[tuple[int, int]]) -> str:
    # One range per line, as rustfmt lays the table out.
    return "\n".join(f"    (0x{lo:04X}, 0x{hi:04X})," for lo, hi in spans)


def render(widths: list[int], spaces: list[int]) -> str:
    wide = ranges([cp for cp, w in enumerate(widths) if w == 2])
    zero = ranges(
        [
            cp
            for cp, w in enumerate(widths)
            if w <= 0 and not 0xD800 <= cp <= 0xDFFF
        ]
    )
    return f"""// GENERATED by scripts/gen_unicode_width.py from the Unicode {VERSION}
// Character Database (UnicodeData.txt, EastAsianWidth.txt, PropList.txt).
// Do not edit by hand; rerun the script.

/// Code points that take 2 columns.
pub(crate) const WIDE: &[(u32, u32)] = &[
{rows(wide)}
];

/// Code points that take no column or do not print.
pub(crate) const ZERO: &[(u32, u32)] = &[
{rows(zero)}
];

/// Code points that separate words: White_Space without the no-break
/// spaces and the controls past ASCII.
pub(crate) const SPACE: &[(u32, u32)] = &[
{rows(ranges(spaces))}
];
"""


def main() -> int:
    category, nobreak = categories(fetch("UnicodeData.txt"))
    east_asian = {
        cp: value
        for span, value in entries(fetch("EastAsianWidth.txt"))
        for cp in span
    }
    props = entries(fetch("PropList.txt"))
    named = {
        name: {cp for span, value in props if value == name for cp in span}
        for name in ("White_Space", "Prepended_Concatenation_Mark")
    }
    concatenation = named["Prepended_Concatenation_Mark"]
    widths = [
        width(
            cp,
            category.get(cp, "Cn"),
            east_asian.get(cp, "N"),
            concatenation,
        )
        for cp in range(0x110000)
    ]
    spaces = sorted(
        cp
        for cp in named["White_Space"]
        if cp not in nobreak and not (cp > 0x7F and category[cp] == "Cc")
    )
    RS_OUT.write_text(render(widths, spaces))
    print(f"Unicode {VERSION}: wrote {RS_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
