import json
import pathlib
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent

PY_OUT = ROOT / "python/mirage/utils/generated/encoding_data.py"
TS_OUT = ROOT / "typescript/packages/core/src/utils/generated/encoding_data.ts"

LICENSE_PY = (ROOT / "scripts/gen_specs.py").read_text().split("\n")[:13]

# The standard as last updated on 21 May 2026, the version
# licenses/third_party/whatwg-encoding.txt names.
SPEC = (
    "https://encoding.spec.whatwg.org/commit-snapshots/"
    "a985b62a9b45c17da3e17a9f0a0b4e30c34c4a8a"
)

# The encoding no label may select: ripgrep looks labels up with
# encoding_rs's for_label_no_replacement, so `-E iso-2022-kr` is an unknown
# encoding (ripgrep 14.1.1).
REFUSED = "replacement"

# Not an index in the standard: each high byte maps to U+F780 plus its
# offset from 0x80.
USER_DEFINED = "x-user-defined"

# The encodings that decode through another one's index.
SHARED_INDEX = {"ISO-8859-8-I": "ISO-8859-8"}

NOTE = (
    "GENERATED by scripts/gen_encoding_tables.py from the WHATWG Encoding\n"
    "Standard of 21 May 2026 (encodings.json and the single-byte indexes;\n"
    "see licenses/third_party/whatwg-encoding.txt). Do not edit by hand;\n"
    "run the script and commit both trees' output together."
)


def fetch(name: str) -> str:
    with urllib.request.urlopen(f"{SPEC}/{name}") as response:
        data: bytes = response.read()
    return data.decode()


def high_half(name: str) -> list[int]:
    if name == USER_DEFINED:
        return [0xF780 + i for i in range(128)]
    points = [0xFFFD] * 128
    index = SHARED_INDEX.get(name, name).lower()
    for line in fetch(f"index-{index}.txt").split("\n"):
        if not line.strip() or line.startswith("#"):
            continue
        pointer, point = line.split()[:2]
        points[int(pointer)] = int(point, 16)
    return points


def rows(points: list[int], indent: str) -> str:
    return "\n".join(
        indent + " ".join(f"0x{p:04X}," for p in points[i : i + 8])
        for i in range(0, len(points), 8)
    )


def render_py(labels: dict[str, str], tables: dict[str, list[int]]) -> str:
    head = "\n".join(LICENSE_PY)
    note = "\n".join(f"# {line}" for line in NOTE.split("\n"))
    label_rows = "\n".join(f'    "{k}": "{v}",' for k, v in labels.items())
    table_rows = "\n".join(
        f'    "{name}": (\n{rows(points, "        ")}\n    ),'
        for name, points in tables.items()
    )
    return f"""{head}

{note}

ENCODING_LABELS: dict[str, str] = {{
{label_rows}
}}

SINGLE_BYTE: dict[str, tuple[int, ...]] = {{
{table_rows}
}}
"""


def render_ts(labels: dict[str, str], tables: dict[str, list[int]]) -> str:
    head = "\n".join(line.replace("#", "//", 1) for line in LICENSE_PY)
    note = "\n".join(f"// {line}" for line in NOTE.split("\n"))
    label_rows = "\n".join(f"  '{k}': '{v}'," for k, v in labels.items())
    table_rows = "\n".join(
        f"  '{name}': [\n{rows(points, '    ')}\n  ],"
        for name, points in tables.items()
    )
    return f"""{head}

{note}

export const ENCODING_LABELS: Readonly<Record<string, string>> = {{
{label_rows}
}}

export const SINGLE_BYTE: Readonly<Record<string, readonly number[]>> = {{
{table_rows}
}}
"""


def main() -> None:
    groups = json.loads(fetch("encodings.json"))
    labels: dict[str, str] = {}
    tables: dict[str, list[int]] = {}
    for group in groups:
        single = group["heading"] == "Legacy single-byte encodings"
        for encoding in group["encodings"]:
            name = encoding["name"]
            if name == REFUSED:
                continue
            for label in encoding["labels"]:
                labels[label] = name
            if single or name == USER_DEFINED:
                tables[name] = high_half(name)
    PY_OUT.write_text(render_py(labels, tables))
    TS_OUT.write_text(render_ts(labels, tables))


if __name__ == "__main__":
    main()
