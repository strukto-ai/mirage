import hashlib
import pathlib
import urllib.request

from gen_unicode_width import VERSION

ROOT = pathlib.Path(__file__).resolve().parent.parent
RS_OUT = ROOT / "rust/mirage-rs/src/generated/unicode_case_fold.rs"

# Unicode's case folding at the version Oniguruma 6.9.10 (the matcher jq
# 1.8.2 builds with) folds by; integ's jq regex cases check the table
# against jq's output.
FILES = {
    "CaseFolding.txt": (
        "6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb"
    ),
}


def fetch(name: str) -> str:
    url = f"https://www.unicode.org/Public/{VERSION}/ucd/{name}"
    request = urllib.request.Request(url, headers={"User-Agent": "mirage"})
    with urllib.request.urlopen(request) as response:
        data: bytes = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != FILES[name]:
        raise SystemExit(f"{name}: sha256 {digest}, want {FILES[name]}")
    return data.decode("utf-8")


def foldings(text: str) -> list[tuple[int, tuple[int, ...]]]:
    """Full case folding: the mappings with status C and F, by code point.

    Status S is the one-character stand-in for an F mapping and T the
    Turkic alternative; a matcher that folds to several characters reads
    neither.
    """
    out = []
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        code, status, mapping = (part.strip() for part in line.split(";")[:3])
        if status in ("C", "F"):
            out.append(
                (int(code, 16), tuple(int(c, 16) for c in mapping.split()))
            )
    return sorted(out)


def render(folds: list[tuple[int, tuple[int, ...]]]) -> str:
    rows = "\n".join(
        f"    (0x{code:04X}, &[{', '.join(f'0x{c:04X}' for c in mapping)}]),"
        for code, mapping in folds
    )
    return f"""// GENERATED by scripts/gen_unicode_case_fold.py from the Unicode
// {VERSION} Character Database (CaseFolding.txt). Do not edit by hand;
// rerun the script.

/// Full case folding (statuses C and F): each code point that folds, and
/// the one to three code points it folds to, by code point.
pub(crate) const FOLDS: &[(u32, &[u32])] = &[
{rows}
];
"""


def main() -> int:
    folds = foldings(fetch("CaseFolding.txt"))
    RS_OUT.write_text(render(folds))
    multi = sum(len(mapping) > 1 for _, mapping in folds)
    print(
        f"Unicode {VERSION}: wrote {RS_OUT.relative_to(ROOT)} "
        f"({len(folds)} foldings, {multi} to several characters)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
