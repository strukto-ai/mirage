import hashlib
import pathlib
import re
import urllib.request

from gen_unicode_width import VERSION

ROOT = pathlib.Path(__file__).resolve().parent.parent
RS_OUT = ROOT / "rust/mirage-rs/src/generated/unicode_blocks.rs"

# Unicode's blocks, which Oniguruma 6.9.10 (the matcher jq 1.8.2 builds
# with) names as `\p{In_Basic_Latin}`.
FILES = {
    "Blocks.txt": (
        "f3907b395d410f1b97342292ca6bc83dd12eb4b205f2a0c48efdef99e517d7b0"
    ),
}


def fetch(name: str) -> str:
    url = f"https://www.unicode.org/Public/{VERSION}/ucd/{name}"
    request = urllib.request.Request(url, headers={"User-Agent": "mirage"})
    with urllib.request.urlopen(request) as response:
        data: bytes = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != FILES[name]:
        raise SystemExit(f"{name}: sha256 {digest}, want {FILES[name]}")
    return data.decode("utf-8")


def blocks(text: str) -> list[tuple[str, int, int]]:
    """Each block's name as Oniguruma matches it, and its range.

    A property name is read with case, spaces, hyphens and underscores
    ignored, and a block's starts with `In`.
    """
    out = []
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        span, name = (part.strip() for part in line.split(";"))
        first, last = span.split("..")
        loose = "in" + re.sub(r"[ _-]", "", name).lower()
        out.append((loose, int(first, 16), int(last, 16)))
    return out


def render(table: list[tuple[str, int, int]]) -> str:
    rows = []
    for name, first, last in table:
        row = f'    ("{name}", 0x{first:04X}, 0x{last:04X}),'
        if len(row.strip().removesuffix(",")) > 60:
            row = (
                f'    (\n        "{name}",\n'
                f"        0x{first:04X},\n        0x{last:04X},\n    ),"
            )
        rows.append(row)
    entries = "\n".join(rows)
    return f"""// GENERATED by scripts/gen_unicode_blocks.py from the Unicode
// {VERSION} Character Database (Blocks.txt). Do not edit by hand; rerun
// the script.

/// Each block as a loosened `\\p{{In...}}` name, and the code points it
/// covers, in code point order.
pub(crate) const BLOCKS: &[(&str, u32, u32)] = &[
{entries}
];
"""


def main() -> int:
    table = blocks(fetch("Blocks.txt"))
    RS_OUT.write_text(render(table))
    print(
        f"Unicode {VERSION}: wrote {RS_OUT.relative_to(ROOT)} ({len(table)} blocks)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
