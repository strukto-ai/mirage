import calendar
import re
import time
from collections.abc import Callable, Sequence
from dataclasses import dataclass, replace
from urllib.parse import urlsplit

# The lines that open every file curl -c writes (curl 8.14.1); readers
# look for the first.
JAR_HEADER = (
    "# Netscape HTTP Cookie File\n"
    "# https://curl.se/docs/http-cookies.html\n"
    "# This file was generated by libcurl! Edit at your own risk.\n\n"
)

# What a cookie file puts before the domain of an HttpOnly cookie.
HTTP_ONLY_PREFIX = "#HttpOnly_"

# No cookie outlives 400 days from its arrival (RFC 6265bis); curl rounds
# the capped time up to a whole minute.
MAX_LIFETIME = 400 * 24 * 60 * 60

# The hosts that take and get a Secure cookie over plain http.
SECURE_HOSTS = frozenset({"localhost", "127.0.0.1", "::1"})

MONTHS = (
    "jan",
    "feb",
    "mar",
    "apr",
    "may",
    "jun",
    "jul",
    "aug",
    "sep",
    "oct",
    "nov",
    "dec",
)

# RFC 822's zones, hours east of UTC.
ZONES = {
    "gmt": 0,
    "ut": 0,
    "utc": 0,
    "z": 0,
    "est": -5,
    "edt": -4,
    "cst": -6,
    "cdt": -5,
    "mst": -7,
    "mdt": -6,
    "pst": -8,
    "pdt": -7,
}

DATE_TOKEN = re.compile(
    r"[+-][0-9]{4}(?![0-9])|[0-9]{1,2}:[0-9]{1,2}(?::[0-9]{1,2})?"
    r"|[A-Za-z]+|[0-9]+"
)
IPV4 = re.compile(r"^[0-9]{1,3}(?:\.[0-9]{1,3}){3}$")


@dataclass(frozen=True, slots=True)
class Cookie:
    name: str
    value: str
    # Without the leading dot a file writes for a domain cookie. None for
    # a Set-Cookie line a file gave without a Domain: it goes to every
    # host and is never saved (curl 8.14.1).
    domain: str | None
    # Whether the cookie also goes to subdomains, which a Domain
    # attribute asks for.
    tailmatch: bool
    # As the server or the file gave it. None for a Set-Cookie line a file
    # gave without a Path: it covers every path, sorts after them all and
    # is saved as ``/`` (curl 8.14.1).
    path: str | None
    secure: bool
    http_only: bool
    # Seconds since the epoch; 0 for a session cookie.
    expires: int
    # Arrival order, which a replaced cookie keeps.
    created: int = 0


def epoch_now() -> int:
    return int(time.time())


def _has_control(text: str) -> bool:
    # A control byte, which no cookie name or value may hold (curl 8.14.1).
    return any(ord(ch) < 0x20 or ord(ch) == 0x7F for ch in text)


def _trim_ws(text: str) -> str:
    # Space and tab off both ends, the blanks RFC 6265 strips.
    return text.strip(" \t")


def parse_date(text: str) -> int | None:
    """The seconds since the epoch an Expires attribute names.

    The forms curl reads: a day of the month, a month name and a year in
    any order, a time (midnight without one), and a zone, RFC 822's
    names or a ``+hhmm`` offset (UTC without one). A two-digit year above
    70 is in the 1900s, the rest in the 2000s, and a date before 1970
    does not parse (curl 8.14.1). Zone names past RFC 822's are a
    deliberate gap: curl knows more of them.

    Args:
        text (str): the attribute's value.

    Returns:
        int | None: the time, None when it does not parse.
    """
    day: int | None = None
    month: int | None = None
    year: int | None = None
    clock: tuple[int, int, int] | None = None
    offset = 0
    for match in DATE_TOKEN.finditer(text):
        token = match.group(0)
        if token[0] in "+-":
            hhmm = int(token[1:])
            sign = -1 if token[0] == "-" else 1
            offset = sign * (hhmm // 100 * 3600 + hhmm % 100 * 60)
        elif ":" in token:
            if clock is not None:
                continue
            parts = [int(part) for part in token.split(":")]
            h, m, s = (*parts, 0, 0)[:3]
            if h > 23 or m > 59 or s > 59:
                return None
            clock = (h, m, s)
        elif token[0].isalpha():
            lower = token.lower()
            if lower[:3] in MONTHS and month is None and len(lower) >= 3:
                month = MONTHS.index(lower[:3])
            elif lower in ZONES:
                offset = ZONES[lower] * 3600
        elif len(token) == 4:
            if year is None:
                year = int(token)
        elif len(token) <= 2:
            n = int(token)
            if day is None:
                day = n
            elif year is None:
                year = 2000 + n if n <= 70 else 1900 + n
        else:
            return None
    if day is None or month is None or year is None or not 1 <= day <= 31:
        return None
    if year < 1970:
        return None
    h, m, s = clock or (0, 0, 0)
    epoch = calendar.timegm((year, month + 1, day, h, m, s)) - offset
    return None if epoch < 0 else epoch


def _target(url: str) -> tuple[str, str, bool] | None:
    """The request a URL makes, as cookie matching sees it.

    Args:
        url (str): the request's URL.

    Returns:
        tuple[str, str, bool] | None: its host, its path and whether it
        is a secure context; None for a URL that does not parse.
    """
    try:
        parts = urlsplit(url)
        host = (parts.hostname or "").lower()
    except ValueError:
        return None
    secure = parts.scheme == "https" or host in SECURE_HOSTS
    return host, parts.path or "/", secure


def _is_ip(host: str) -> bool:
    return IPV4.match(host) is not None or ":" in host


def default_path(path: str) -> str:
    """The path a cookie set without one takes.

    The request's up to and including its last slash. curl keeps that
    slash, which RFC 6265 drops, and the matching below ignores it.

    Args:
        path (str): the request's path.
    """
    cut = path.rfind("/")
    return "/" if cut <= 0 else path[: cut + 1]


def _path_key(cookie_path: str | None) -> str:
    # The path a cookie matches with: one that does not start with a
    # slash covers everything, and a trailing slash is dropped (curl
    # 8.14.1).
    if cookie_path is None or not cookie_path.startswith("/"):
        return "/"
    if len(cookie_path) > 1 and cookie_path.endswith("/"):
        return cookie_path[:-1]
    return cookie_path


def path_matches(cookie_path: str | None, path: str) -> bool:
    """Whether a cookie's path covers a request's.

    RFC 6265's rule, the same path or one below it, over the path the
    cookie matches with.

    Args:
        cookie_path (str | None): the cookie's path as stored.
        path (str): the request's path.
    """
    own = _path_key(cookie_path)
    if path == own:
        return True
    return path.startswith(own) and (
        own.endswith("/") or path[len(own) : len(own) + 1] == "/"
    )


def _domain_matches(cookie: Cookie, host: str) -> bool:
    if cookie.domain is None:
        return True
    domain = cookie.domain.lower()
    return host == domain or (cookie.tailmatch and host.endswith(f".{domain}"))


def _same_cookie(a: Cookie, b: Cookie) -> bool:
    return (
        a.name == b.name
        and (a.domain or "").lower() == (b.domain or "").lower()
        and _path_key(a.path) == _path_key(b.path)
    )


def cookie_value(part: str | None, typed: str | None) -> str | None:
    """The Cookie value a request carries: the jar's part, then the typed.

    A deliberate divergence: curl sends the two as separate Cookie lines,
    and one line joined with ``; `` reads the same to a server (node joins
    them so).

    Args:
        part (str | None): the jar's cookies for the request.
        typed (str | None): the Cookie header the line typed with -H.
    """
    pieces = [piece for piece in (part, typed) if piece]
    return "; ".join(pieces) if pieces else None


class CookieJar:
    """curl's cookie engine for one invocation.

    What -b loads, what each response sets, what each request sends, and
    the file -c writes. Matching follows curl 8.14.1 where it parts from
    RFC 6265: a Secure cookie also rides plain http to localhost,
    127.0.0.1 and ::1, and a request sends longer paths first, then
    longer names, then newer cookies. One deliberate gap: curl refuses a
    Domain that is a public suffix (co.uk) through the public suffix
    list, whose license mirage cannot ship, so only a suffix of one label
    (com) is refused here. A host-only cookie's domain is the host
    lowercase, as the URL parser hands it over, where curl keeps it as
    typed.
    """

    def __init__(
        self,
        engine: bool,
        literal: str | None = None,
        now: Callable[[], int] = epoch_now,
    ) -> None:
        """Start an empty jar.

        Args:
            engine (bool): whether the jar keeps what responses set: on
                once the line names a cookie file or -c, off for literal
                -b data alone (curl 8.14.1).
            literal (str | None): the literal -b data, sent to every host
                after the jar's cookies.
            now (Callable[[], int]): the clock, in seconds since the
                epoch.
        """
        self.engine = engine
        self.literal = literal
        self.now = now
        # Oldest first.
        self.cookies: list[Cookie] = []
        # The jar's part of each request's Cookie header, in the order
        # sent; curl -v shows it per hop.
        self.sent: list[str | None] = []
        self._arrivals = 0

    def _keep(self, cookie: Cookie, expired: bool) -> None:
        index = next(
            (
                i
                for i, other in enumerate(self.cookies)
                if _same_cookie(other, cookie)
            ),
            -1,
        )
        if expired:
            if index >= 0:
                del self.cookies[index]
            return
        if index >= 0:
            self.cookies[index] = replace(
                cookie, created=self.cookies[index].created
            )
            return
        self._arrivals += 1
        self.cookies.append(replace(cookie, created=self._arrivals))

    def _add(self, header: str, url: str | None) -> None:
        """Add one Set-Cookie value.

        Args:
            header (str): the header's value.
            url (str | None): the request it answered, None for a line a
                file gave, which no host, path or scheme constrains.
        """
        request = None if url is None else _target(url)
        if url is not None and request is None:
            return
        pair, *attributes = header.split(";")
        eq = pair.find("=")
        if eq < 0:
            return
        name = _trim_ws(pair[:eq])
        value = _trim_ws(pair[eq + 1 :])
        if _has_control(name) or _has_control(value):
            return
        expires_at: int | None = None
        max_age: int | None = None
        domain_attr: str | None = None
        path_attr: str | None = None
        secure = False
        http_only = False
        for attribute in attributes:
            sep = attribute.find("=")
            key = _trim_ws(attribute if sep < 0 else attribute[:sep]).lower()
            raw = "" if sep < 0 else _trim_ws(attribute[sep + 1 :])
            if key == "expires":
                parsed = parse_date(raw)
                expires_at = expires_at if parsed is None else parsed
            elif key == "max-age":
                # curl drops a cookie whose Max-Age does not start with a
                # digit or a minus, and reads the digits that lead one
                # that does.
                digits = re.match(r"-?[0-9]+", raw)
                if digits is None:
                    return
                max_age = int(digits.group(0))
            elif key == "domain":
                if raw:
                    domain_attr = raw.removeprefix(".")
            elif key == "path":
                path_attr = raw
            elif key == "secure":
                secure = True
            elif key == "httponly":
                http_only = True
        now = self.now()
        expires = 0
        expired = False
        if max_age is not None:
            expired = max_age <= 0
            expires = 0 if expired else now + min(max_age, MAX_LIFETIME + 1)
        elif expires_at is not None:
            expired = expires_at <= now
            expires = expires_at
        if expires > now + MAX_LIFETIME:
            expires = -(-(now + MAX_LIFETIME) // 60) * 60
        domain = domain_attr
        tailmatch = domain_attr is not None
        path = path_attr
        if request is not None:
            host, request_path, secure_context = request
            if path_attr is None:
                path = default_path(request_path)
            if domain_attr is None:
                domain = host
            else:
                wanted = domain_attr.lower()
                if _is_ip(host):
                    if wanted != host:
                        return
                    domain = host
                    tailmatch = False
                elif wanted == host or host.endswith(f".{wanted}"):
                    if "." not in wanted and wanted != host:
                        return
                else:
                    return
            if secure and not secure_context:
                return
            if name.startswith("__Secure-") and not secure:
                return
            if name.startswith("__Host-") and (
                not secure or tailmatch or path != "/"
            ):
                return
        self._keep(
            Cookie(
                name=name,
                value=value,
                domain=domain,
                tailmatch=tailmatch,
                path=path,
                secure=secure,
                http_only=http_only,
                expires=expires,
            ),
            expired,
        )

    def store(self, url: str, headers: Sequence[str]) -> None:
        """Keep what one response to ``url`` set.

        Args:
            url (str): the request the response answered.
            headers (Sequence[str]): its Set-Cookie values, in wire order.
        """
        if not self.engine:
            return
        for header in headers:
            self._add(header, url)

    def load(self, text: str) -> None:
        """Load a cookie file.

        curl's tab-separated lines, ``#HttpOnly_`` marking a domain, or
        ``Set-Cookie:`` header lines. A line that does not parse, and a
        cookie already expired, are skipped (curl 8.14.1).

        Args:
            text (str): the file's text.
        """
        for raw in text.split("\n"):
            line = raw.removesuffix("\r")
            if line[: len("set-cookie:")].lower() == "set-cookie:":
                self._add(line[len("set-cookie:") :].lstrip(), None)
                continue
            http_only = False
            if line.startswith(HTTP_ONLY_PREFIX):
                http_only = True
                line = line[len(HTTP_ONLY_PREFIX) :]
            elif not line or line.startswith("#"):
                continue
            fields = line.split("\t")
            if len(fields) == 6:
                fields.append("")
            if len(fields) != 7:
                continue
            domain, tail, path, secure, expiry, name, value = fields
            digits = re.match(r"[0-9]+", expiry)
            if digits is None:
                continue
            expires = int(digits.group(0))
            if expires != 0 and expires <= self.now():
                continue
            self._keep(
                Cookie(
                    name=name,
                    value=value,
                    domain=domain.removeprefix("."),
                    tailmatch=tail.upper() == "TRUE",
                    path=path,
                    secure=secure.upper() == "TRUE",
                    http_only=http_only,
                    expires=expires,
                ),
                False,
            )

    def header(self, url: str) -> str | None:
        """The jar's part of the Cookie header a request to ``url`` sends.

        Args:
            url (str): the request's URL.
        """
        request = _target(url)
        now = self.now()
        pairs: list[str] = []
        if self.engine and request is not None:
            host, path, secure_context = request
            matched = [
                c
                for c in self.cookies
                if (c.expires == 0 or c.expires > now)
                and _domain_matches(c, host)
                and path_matches(c.path, path)
                and (not c.secure or secure_context)
            ]
            matched.sort(
                key=lambda c: (-len(c.path or ""), -len(c.name), -c.created)
            )
            pairs = [f"{c.name}={c.value}" for c in matched]
        if self.literal is not None:
            pairs.append(self.literal)
        value = "; ".join(pairs) if pairs else None
        self.sent.append(value)
        return value

    def render(self) -> str:
        """The file -c writes: every live cookie with a domain, newest first."""
        now = self.now()
        live = [
            c
            for c in self.cookies
            if c.domain is not None and (c.expires == 0 or c.expires > now)
        ]
        live.sort(key=lambda c: -c.created)
        lines = (
            "\t".join(
                (
                    f"{HTTP_ONLY_PREFIX if c.http_only else ''}"
                    f"{'.' if c.tailmatch else ''}{c.domain}",
                    "TRUE" if c.tailmatch else "FALSE",
                    "/" if c.path is None else c.path,
                    "TRUE" if c.secure else "FALSE",
                    str(c.expires),
                    c.name,
                    c.value,
                )
            )
            for c in live
        )
        return JAR_HEADER + "".join(f"{line}\n" for line in lines)
