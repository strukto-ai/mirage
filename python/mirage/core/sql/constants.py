from stat import S_IFREG

from mirage.utils.stat_view import DIR_MODE, S_IFMT
from mirage.vfs.sql.types import SqlDialect

# The inode every path resolves from.
ROOT_INO = 1

# The bytes one ``fs_data`` row holds in a database the mount makes:
# AgentFS's default. A database made with another size keeps it
# (``fs_config``), and the ops read and write rows of that size.
DEFAULT_CHUNK_SIZE = 4096

# The AgentFS schema the tables follow, as ``fs_config`` records it.
SCHEMA_VERSION = "0.4"

# The most parameters one statement binds: D1 and Durable Objects stop
# at 100.
MAX_PARAMS = 100

# The bytes a streamed write gathers before it lands them.
FLUSH_BYTES = 1024 * 1024

# The columns of ``fs_inode`` the ops read.
INODE_COLUMNS: tuple[str, ...] = (
    "ino",
    "mode",
    "nlink",
    "uid",
    "gid",
    "size",
    "atime",
    "atime_nsec",
    "mtime",
    "mtime_nsec",
    "ctime",
    "ctime_nsec",
)


def columns(alias: str) -> str:
    """``INODE_COLUMNS`` read off the table aliased ``alias``."""
    return ", ".join(f"{alias}.{c}" for c in INODE_COLUMNS)


# The rows a fresh database starts with: AgentFS's chunk size and schema
# version. Each is a no-op on a database that has it, so opening one
# another runtime made keeps what it holds.
_SEED: tuple[str, ...] = (
    f"""INSERT INTO fs_config (key, value) SELECT 'chunk_size', '{DEFAULT_CHUNK_SIZE}'
    WHERE NOT EXISTS (SELECT 1 FROM fs_config WHERE key = 'chunk_size')""",
    f"""INSERT INTO fs_config (key, value) SELECT 'schema_version', '{SCHEMA_VERSION}'
    WHERE NOT EXISTS (SELECT 1 FROM fs_config WHERE key = 'schema_version')""",
)

# The tables a database holds a filesystem in, by dialect: AgentFS's
# (``fs_config``, ``fs_inode``, ``fs_dentry``, ``fs_data``,
# ``fs_symlink``), so a database either one made the other mounts. The
# index on ``fs_dentry(ino)`` is the mount's own, so counting an inode's
# links reads no other rows. In Postgres the root is inode 1, so the
# generated numbers start past it.
SCHEMA: dict[SqlDialect, tuple[str, ...]] = {
    SqlDialect.SQLITE: (
        "CREATE TABLE IF NOT EXISTS fs_config"
        " (key TEXT PRIMARY KEY, value TEXT NOT NULL)",
        """CREATE TABLE IF NOT EXISTS fs_inode (
      ino INTEGER PRIMARY KEY AUTOINCREMENT, mode INTEGER NOT NULL,
      nlink INTEGER NOT NULL DEFAULT 0, uid INTEGER NOT NULL DEFAULT 0,
      gid INTEGER NOT NULL DEFAULT 0, size INTEGER NOT NULL DEFAULT 0,
      atime INTEGER NOT NULL, mtime INTEGER NOT NULL, ctime INTEGER NOT NULL,
      rdev INTEGER NOT NULL DEFAULT 0, atime_nsec INTEGER NOT NULL DEFAULT 0,
      mtime_nsec INTEGER NOT NULL DEFAULT 0, ctime_nsec INTEGER NOT NULL DEFAULT 0)""",
        """CREATE TABLE IF NOT EXISTS fs_dentry (
      id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL,
      parent_ino INTEGER NOT NULL, ino INTEGER NOT NULL, UNIQUE(parent_ino, name))""",
        "CREATE INDEX IF NOT EXISTS idx_fs_dentry_parent"
        " ON fs_dentry(parent_ino, name)",
        "CREATE INDEX IF NOT EXISTS idx_fs_dentry_ino ON fs_dentry(ino)",
        """CREATE TABLE IF NOT EXISTS fs_data (
      ino INTEGER NOT NULL, chunk_index INTEGER NOT NULL, data BLOB NOT NULL,
      PRIMARY KEY (ino, chunk_index))""",
        "CREATE TABLE IF NOT EXISTS fs_symlink"
        " (ino INTEGER PRIMARY KEY, target TEXT NOT NULL)",
        *_SEED,
    ),
    SqlDialect.POSTGRES: (
        "CREATE TABLE IF NOT EXISTS fs_config"
        " (key TEXT PRIMARY KEY, value TEXT NOT NULL)",
        """CREATE TABLE IF NOT EXISTS fs_inode (
      ino BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
      mode BIGINT NOT NULL, nlink BIGINT NOT NULL DEFAULT 0,
      uid BIGINT NOT NULL DEFAULT 0, gid BIGINT NOT NULL DEFAULT 0,
      size BIGINT NOT NULL DEFAULT 0, atime BIGINT NOT NULL, mtime BIGINT NOT NULL,
      ctime BIGINT NOT NULL, rdev BIGINT NOT NULL DEFAULT 0,
      atime_nsec BIGINT NOT NULL DEFAULT 0, mtime_nsec BIGINT NOT NULL DEFAULT 0,
      ctime_nsec BIGINT NOT NULL DEFAULT 0)""",
        """CREATE TABLE IF NOT EXISTS fs_dentry (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,
      parent_ino BIGINT NOT NULL, ino BIGINT NOT NULL, UNIQUE(parent_ino, name))""",
        "CREATE INDEX IF NOT EXISTS idx_fs_dentry_parent"
        " ON fs_dentry(parent_ino, name)",
        "CREATE INDEX IF NOT EXISTS idx_fs_dentry_ino ON fs_dentry(ino)",
        """CREATE TABLE IF NOT EXISTS fs_data (
      ino BIGINT NOT NULL, chunk_index BIGINT NOT NULL, data BYTEA NOT NULL,
      PRIMARY KEY (ino, chunk_index))""",
        "CREATE TABLE IF NOT EXISTS fs_symlink"
        " (ino BIGINT PRIMARY KEY, target TEXT NOT NULL)",
        *_SEED,
    ),
}

# How a statement names the inode the statement before it inserted, by
# dialect.
LAST_INO: dict[SqlDialect, str] = {
    SqlDialect.SQLITE: "last_insert_rowid()",
    SqlDialect.POSTGRES: "currval(pg_get_serial_sequence('fs_inode', 'ino'))",
}

# Every fixed statement the sql ops run, by name. TypeScript's ``SQL``
# holds the same text, so the two runtimes read and write one database
# alike. ``seed_root`` makes the root at the time ``?`` gives unless the
# database has one; the casts type the parameters, which a SELECT list
# leaves untyped in Postgres. ``subtree`` is every entry under one
# directory, each with its depth below it and its path from it.
SQL: dict[str, str] = {
    "chunk_size": "SELECT value FROM fs_config WHERE key = 'chunk_size'",
    "seed_root": f"""INSERT INTO fs_inode
    (ino, mode, nlink, uid, gid, size, atime, mtime, ctime)
    SELECT {ROOT_INO}, {DIR_MODE}, 1, 0, 0, 0,
      CAST(? AS BIGINT), CAST(? AS BIGINT), CAST(? AS BIGINT)
    WHERE NOT EXISTS (SELECT 1 FROM fs_inode WHERE ino = {ROOT_INO})""",
    "children": f"""SELECT d.name, {columns("i")}
    FROM fs_dentry d JOIN fs_inode i ON i.ino = d.ino
    WHERE d.parent_ino = ?""",
    "has_child": "SELECT 1 AS hit FROM fs_dentry WHERE parent_ino = ? LIMIT 1",
    "has_entry": "SELECT 1 AS hit FROM fs_dentry WHERE parent_ino = ? AND name = ?",
    "subtree": f"""WITH RECURSIVE tree (id, ino, depth, rel) AS (
      SELECT id, ino, 1, name FROM fs_dentry WHERE parent_ino = ?
      UNION ALL
      SELECT d.id, d.ino, t.depth + 1, t.rel || '/' || d.name
      FROM fs_dentry d JOIN tree t ON d.parent_ino = t.ino)
    SELECT t.id, t.depth, t.rel, {columns("i")}
    FROM tree t JOIN fs_inode i ON i.ino = t.ino""",
    "chunks": """SELECT chunk_index, data FROM fs_data
    WHERE ino = ? AND chunk_index >= ? AND chunk_index <= ? ORDER BY chunk_index""",
    "used_bytes": "SELECT COALESCE(SUM(size), 0) AS n FROM fs_inode"
    f" WHERE (mode & {S_IFMT}) = {S_IFREG}",
    "new_inode": """INSERT INTO fs_inode
    (mode, nlink, uid, gid, size, atime, atime_nsec,
    mtime, mtime_nsec, ctime, ctime_nsec)
    VALUES (?, 1, 0, 0, ?, ?, ?, ?, ?, ?, ?)""",
    "remove_entry": "DELETE FROM fs_dentry WHERE parent_ino = ? AND name = ?",
    "move_entry": "UPDATE fs_dentry SET parent_ino = ?, name = ?"
    " WHERE parent_ino = ? AND name = ?",
}

# What ``restore`` empties before it writes a snapshot back.
CLEAR: tuple[str, ...] = (
    "DELETE FROM fs_data",
    "DELETE FROM fs_symlink",
    "DELETE FROM fs_dentry",
    f"DELETE FROM fs_inode WHERE ino <> {ROOT_INO}",
)
